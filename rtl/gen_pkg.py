#!/usr/bin/env python
"""Generate rtl/src/tcta_isa_pkg.sv from sim/tcta/encode.py, so the RTL decoder and the Python encoder have one
source for opcodes, field positions, flags, qualifier tables, dtype codes and the loop-variant field map.

    python rtl/gen_pkg.py        # rewrites rtl/src/tcta_isa_pkg.sv
"""
from __future__ import annotations

import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, "..", "sim"))

from tcta.encode import (DTYPES, EXT, FIELD_SPECS, FLAG, FLAG_NEXT_SHIFT, INCR_FIELDS, OPCODES, QUAL_TABLES,  # noqa: E402
                         QUEUES, SPS)
from tcta.isa import EDGES, Q  # noqa: E402

POS_CODE = {"A": 0, "B": 1, "C": 2, "D": 3, "imm": 4, "imm_hi": 5, "imm_lo": 6, "B_lo": 7, "B_hi": 8}


def ident(op: str) -> str:
    return op.replace(".", "_")


def main():
    out = []
    w = out.append
    w("// Generated by rtl/gen_pkg.py from sim/tcta/encode.py -- do not edit.")
    w("package tcta_isa_pkg;")
    w("  // queues (word[127:125]) and scratchpads (tile reference [15:12])")
    for i, q in enumerate(QUEUES):
        w(f"  localparam logic [2:0] Q_{q.value} = 3'd{i};")
    for i, sp in enumerate(SPS):
        w(f"  localparam logic [3:0] SP_{sp.value} = 4'd{i};")
    w("  // opcodes (word[124:119])")
    for i, op in enumerate(OPCODES):
        w(f"  localparam logic [5:0] OP_{ident(op)} = 6'd{i};")
    w(f"  localparam logic [5:0] OP_EXT = 6'd{EXT};")
    w(f"  localparam int N_OPCODES = {len(OPCODES)};")
    w("  // flags (word[111:96])")
    for name, bit in FLAG.items():
        w(f"  localparam int FL_{name.upper()} = {bit};")
    w(f"  localparam int FL_NEXT_SHIFT = {FLAG_NEXT_SHIFT};")
    w("  // qualifier tables")
    for tname, vals in QUAL_TABLES.items():
        for i, v in enumerate(vals):
            w(f"  localparam logic [6:0] QUAL_{tname.upper()}_{v.upper()} = 7'd{i};")
    w("  // DRAM dtype codes (descriptor byte 44)")
    for i, d in enumerate(DTYPES):
        w(f"  localparam logic [7:0] DT_{ident(d).upper()} = 8'd{i};")
    w("  // loop-variant field ids (extension word entry [45:40]) and kinds [47:46]")
    for i, f in enumerate(INCR_FIELDS):
        w(f"  localparam logic [5:0] IF_{ident(f).replace('.', '_').upper()} = 6'd{i};")
    w("  localparam logic [1:0] IK_ADD = 2'd0, IK_SLOT = 2'd1, IK_MOD = 2'd2;")
    w("  // token edges (ISA 8.1): edge index = producer*8 + consumer; EDGE_VALID marks the legal ones")
    w("  function automatic int edge_id(input logic [2:0] from_q, input logic [2:0] to_q);")
    w("    return int'(from_q) * 8 + int'(to_q);")
    w("  endfunction")
    valid = ["1'b0"] * 64
    for a, b in EDGES:
        valid[QUEUES.index(a) * 8 + QUEUES.index(b)] = "1'b1"
    w("  localparam logic [63:0] EDGE_VALID = {" + ", ".join(reversed(valid)) + "};")
    w("  // where each loop-variant field of each opcode lives in the word (position code) -- the front end adds")
    w("  // i*step there. Position codes: 0 A, 1 B, 2 C, 3 D, 4 imm, 5 imm_hi, 6 imm_lo, 7 B_lo, 8 B_hi; 15 = none.")
    w("  // region.base / region.scales_base are carried as separate offsets beside the word (see tcta_pkg::instr_t).")
    w("  function automatic logic [3:0] incr_pos(input logic [5:0] opcode, input logic [5:0] field);")
    w("    incr_pos = 4'd15;")
    w("    case (opcode)")
    for i, op in enumerate(OPCODES):
        entries = []
        for f in FIELD_SPECS[op]:
            if f.name in INCR_FIELDS and f.kind not in ("flag", "queue") and not f.kind.startswith("qual"):
                entries.append((INCR_FIELDS.index(f.name), POS_CODE[f.pos]))
        if entries:
            w(f"      OP_{ident(op)}: case (field)")
            for fid, pos in entries:
                w(f"        6'd{fid}: incr_pos = 4'd{pos};")
            w("        default: incr_pos = 4'd15;")
            w("      endcase")
    w("      default: incr_pos = 4'd15;")
    w("    endcase")
    w("  endfunction")
    w("endpackage")
    path = os.path.join(HERE, "src", "tcta_isa_pkg.sv")
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w") as fh:
        fh.write("\n".join(out) + "\n")
    print("wrote", path, len(out), "lines")


if __name__ == "__main__":
    main()
